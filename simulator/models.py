"""
Data models and representations for Lamport's Distributed Mutual Exclusion Algorithm.
"""

from enum import Enum
from dataclasses import dataclass, field, asdict
from typing import Optional, Dict, Any
import time
import uuid


class MessageType(str, Enum):
    """Types of messages in Lamport's Mutual Exclusion Algorithm."""
    REQUEST = "REQUEST"
    REPLY = "REPLY"
    RELEASE = "RELEASE"


class ProcessState(str, Enum):
    """Operating states of a distributed process."""
    RELEASED = "RELEASED"                  # Idle / outside Critical Section
    REQUESTING = "REQUESTING"              # Broadcasted request, waiting for replies
    WAITING = "WAITING"                    # Has all replies, waiting for queue head or vice-versa
    IN_CRITICAL_SECTION = "IN_CRITICAL_SECTION"  # Actively executing inside Critical Section


@dataclass(order=True)
class RequestEntry:
    """
    Represents an entry in a process's local request queue.
    Ordered by (timestamp, process_id) tie-breaker.
    Smaller timestamp first; if equal, smaller process_id first.
    """
    timestamp: int
    process_id: int

    def to_dict(self) -> Dict[str, Any]:
        return {
            "timestamp": self.timestamp,
            "process_id": self.process_id,
            "display": f"(T={self.timestamp}, P{self.process_id})"
        }

    def __str__(self) -> str:
        return f"(T={self.timestamp}, P{self.process_id})"


@dataclass
class Message:
    """
    Represents a distributed message passed between processes.
    Simulates asynchronous network transmission.
    """
    id: str
    msg_type: MessageType
    sender_id: int
    receiver_id: int
    timestamp: int          # Lamport timestamp of the sender when the message was sent
    req_timestamp: int      # Timestamp of the original resource request
    status: str = "in_transit"  # 'in_transit' or 'delivered'
    step_created: int = 0
    step_delivered: Optional[int] = None
    created_at: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "msg_type": self.msg_type.value if isinstance(self.msg_type, MessageType) else str(self.msg_type),
            "sender_id": self.sender_id,
            "receiver_id": self.receiver_id,
            "timestamp": self.timestamp,
            "req_timestamp": self.req_timestamp,
            "status": self.status,
            "step_created": self.step_created,
            "step_delivered": self.step_delivered,
            "created_at": self.created_at
        }

    @classmethod
    def create(
        cls,
        msg_type: MessageType,
        sender_id: int,
        receiver_id: int,
        timestamp: int,
        req_timestamp: int,
        step_created: int = 0
    ) -> 'Message':
        short_id = f"MSG-{msg_type.value[:3]}-{sender_id}->{receiver_id}-{uuid.uuid4().hex[:6]}"
        return cls(
            id=short_id,
            msg_type=msg_type,
            sender_id=sender_id,
            receiver_id=receiver_id,
            timestamp=timestamp,
            req_timestamp=req_timestamp,
            step_created=step_created
        )


@dataclass
class Event:
    """
    Represents a timeline log event generated by the simulator.
    Carries educational explanations to facilitate learning and viva demonstrations.
    """
    id: int
    step: int
    event_type: str  # 'REQUEST', 'REPLY', 'RELEASE', 'CS_ENTRY', 'CS_EXIT', 'SYSTEM'
    process_id: Optional[int]
    description: str
    educational_note: str
    timestamp: float = field(default_factory=time.time)
    details: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "step": self.step,
            "event_type": self.event_type,
            "process_id": self.process_id,
            "description": self.description,
            "educational_note": self.educational_note,
            "details": self.details,
            "timestamp": self.timestamp
        }
